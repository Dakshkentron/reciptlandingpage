function classify(name: string): Category {
  const lower = name.toLowerCase();
  for (const [pattern, category] of categoryRules) {
    if (pattern.test(lower)) return category;
  }
  return 'Other';
}

export const integrationCatalog: Integration[] = [
  ...connected.map(([name, auth, detail]): Integration => ({
    name, status: 'connected', auth, detail, category: classify(name),
  })),
  ...ready.map(([name, auth]): Integration => ({
    name, status: 'ready', auth, category: classify(name),
  })),
  ...comingSoon.map((name): Integration => ({
    name, status: 'coming-soon', auth: 'Coming soon', category: classify(name),
  })),
].sort((a, b) => a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }));

/** Category counts, used to label and order the directory filter pills. */
export const categoryCounts = categories.reduce<Record<Category, number>>((acc, category) => {
  acc[category] = integrationCatalog.filter((i) => i.category === category).length;
  return acc;
}, {} as Record<Category, number>);

export function isPopular(name: string) {
  return popularSet.has(name);
}

